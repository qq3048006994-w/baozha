async function newPage(width=1440,height=1000){
 const context=await browser.newContext({viewport:{width,height}})
 await context.addInitScript(()=>localStorage.setItem('kaizha.settings.v1',JSON.stringify({speed:0,motion:false})))
 const page=await context.newPage()
 page.on('pageerror',e=>errors.push(e.message))
 page.on('console',msg=>{if(msg.type()==='error') errors.push(msg.text())})
 page.setDefaultTimeout(10000)
 await page.goto(process.env.KAIZHA_URL || 'http://127.0.0.1:5173/',{waitUntil:'networkidle'})
 return page
}
async function click(page,name,exact=false){await page.getByRole('button',{name,exact}).click()}
async function close(page){await click(page,'关闭面板',true)}
async function start(page){await click(page,'开始审案'); for(let i=0;i<3;i++) await click(page,'继续案前叙'); await click(page,'惊堂木落')}
